#!/usr/bin/env node
// koru-vercel — turnkey hosting of a Koru/Orisha site on Vercel.
//
//   koru-vercel build [--root DIR] [--fallback FILE] [--name NAME] [projDir]
//       Embed a completely static site (DIR, default ./public) into an Orisha
//       wasm reactor and stage a Vercel deploy dir (default ./deploy).
//
//   koru-vercel dev  [projDir]
//       Run the staged deploy dir through the real adapter locally.
//
//   koru-vercel deploy [projDir]
//       build, then `vercel deploy --prod --yes` on the staged dir.
//
// What this automates is the gap the codebase kept hand-assembling: bake the
// site → compile to a wasm reactor → scaffold the adapter → ship. A static site
// needs no Koru of your own; author `main.k` (pure Koru) to put Orisha in the
// loop for custom routes.
//
// Discovery (override with env):
//   KORUC        the koru compiler   (default: $KORU_REPO/zig-out/bin/koruc)
//   KORU_STDLIB  the standard lib    (default: $KORU_REPO/koru_std)
//   ORISHA_PATH  the orisha/lib dir  (default: $HOME/src/orisha/lib)

import { execFileSync, spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SCAFFOLD = join(here, "..", "scaffold");

const KORU_REPO = process.env.KORU_REPO ?? `${homedir()}/src/koru`;
const KORUC = process.env.KORUC ?? join(KORU_REPO, "zig-out", "bin", "koruc");
const KORU_STDLIB = process.env.KORU_STDLIB ?? join(KORU_REPO, "koru_std");
const ORISHA_PATH = process.env.ORISHA_PATH ?? `${homedir()}/src/orisha/lib`;

const SCAFFOLD_FILES = [
  "serve.mjs",
  "vercel.json",
  "test-adapter.mjs",
  ".vercelignore",
  ".gitignore",
  "package.json",
];

function fail(msg) {
  console.error(`✗ ${msg}`);
  process.exit(1);
}

function entryTemplate({ name, root, fallback }) {
  // The proven Orisha wasm reactor: embed the site, route it, expose the three
  // host windows. `root` is resolved relative to this file's directory (build/).
  return `// Generated by koru-vercel build. Do not edit — re-run the command.
const std = @import("std");

~import orisha
~import std/build

~std/build:config {
    "target": "wasm32-freestanding"
}
~std/build:requires {
    exe.entry = .disabled;
    exe.rdynamic = true;
    exe.root_module.link_libc = false;
    exe.root_module.optimize = .ReleaseSmall;
}

~orisha:static(name: "${name}", root: "${root}", fallback: "${fallback}")

~orisha:handler = orisha:static-router(name: "${name}")

// --- The host seam. Request windows in, answer bytes out. ---
var request_buf: [8192]u8 = undefined;
var out_ptr: [*]const u8 = undefined;
var out_len: usize = 0;

export fn request_ptr() [*]u8          { return &request_buf; }
export fn request_cap() u32            { return @intCast(request_buf.len); }
export fn response_ptr() [*]const u8   { return out_ptr; }

export fn handle(raw_len: u32) u32 {
    const raw = request_buf[0..@min(raw_len, request_buf.len)];
    const answer = koru_orisha.answer_event.handler(.{ .raw = raw });
    if (answer.body.len == 0) {
        out_ptr = answer.head.ptr;
        out_len = answer.head.len;
        return @intCast(out_len);
    }
    return 0;
}
`;
}

function parseArgs(argv) {
  const args = { proj: ".", root: "public", fallback: "200.html", name: "site", backend: null, dynamic: null, link: null };
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--root") args.root = argv[++i];
    else if (a === "--fallback") args.fallback = argv[++i];
    else if (a === "--name") args.name = argv[++i];
    else if (a === "--backend") args.backend = argv[++i];
    else if (a === "--dynamic") args.dynamic = argv[++i];
    else if (a === "--link") args.link = argv[++i];
    else if (a.startsWith("--")) fail(`unknown option: ${a}`);
    else rest.push(a);
  }
  if (rest.length > 1) fail(`expected at most one project dir, got: ${rest.join(" ")}`);
  if (rest.length === 1) args.proj = rest[0];

  if (args.backend && args.dynamic === null) {
    fail("--backend requires --dynamic (comma-separated path prefixes to proxy)");
  }
  if (args.dynamic !== null && args.backend === null) {
    fail("--dynamic requires --backend");
  }
  args.hybrid = args.backend !== null;
  args.dynamicList = args.dynamic ? args.dynamic.split(",").map((s) => s.trim()).filter(Boolean) : null;
  return args;
}

function discover() {
  if (!existsSync(KORUC)) fail(`koruc not found at ${KORUC} (set KORUC or KORU_REPO)`);
  if (!existsSync(KORU_STDLIB)) fail(`std not found at ${KORU_STDLIB} (set KORU_STDLIB)`);
  if (!existsSync(ORISHA_PATH)) fail(`orisha not found at ${ORISHA_PATH} (set ORISHA_PATH)`);
  return { koruc: KORUC, std: KORU_STDLIB, orisha: ORISHA_PATH };
}

function build(args) {
  const { koruc, std, orisha } = discover();
  const proj = resolve(args.proj);
  const rootAbs = resolve(proj, args.root);
  if (!existsSync(rootAbs)) fail(`static root not found: ${rootAbs}`);
  if (!existsSync(join(rootAbs, args.fallback))) {
    console.warn(`⚠ fallback '${args.fallback}' not present in ${rootAbs} — unknown paths will 404.`);
  }

  const buildDir = join(proj, "build");
  const deployDir = join(proj, "deploy");
  mkdirSync(buildDir, { recursive: true });
  mkdirSync(deployDir, { recursive: true });

  // Root, relative from buildDir to the static dir, for the embedded path.
  const relRoot = relative(buildDir, rootAbs);
  writeFileSync(
    join(buildDir, "main.kz"),
    entryTemplate({ name: args.name, root: relRoot, fallback: args.fallback }),
  );
  writeFileSync(
    join(buildDir, "koru.json"),
    JSON.stringify({ name: args.name, paths: { std, orisha } }, null, 2) + "\n",
  );

  console.log(`→ compiling ${join(buildDir, "main.kz")} (embeds ${rootAbs})`);
  const r = spawnSync(koruc, ["build", "main.kz"], { cwd: buildDir, stdio: "inherit" });
  if (r.status !== 0) fail("koruc build failed (see above)");

  const wasm = join(buildDir, "a.out");
  if (!existsSync(wasm)) fail(`compiler did not produce ${wasm}`);
  mkdirSync(join(deployDir, "wasm"), { recursive: true });
  mkdirSync(join(deployDir, "api"), { recursive: true });
  cpSync(wasm, join(deployDir, "wasm", "handler.wasm"));

  for (const f of SCAFFOLD_FILES) {
    const dst = f === "serve.mjs" ? join(deployDir, "api", f) : join(deployDir, f);
    if (f === "serve.mjs" && args.hybrid) {
      // Hybrid mode: parameterize the reverse-proxy adapter with the site config.
      const tpl = readFileSync(join(SCAFFOLD, "serve.hybrid.mjs"), "utf-8")
        .replaceAll("__BACKEND__", args.backend)
        .replaceAll("__DYNAMIC_JSON__", JSON.stringify(args.dynamicList));
      writeFileSync(dst, tpl);
    } else {
      cpSync(join(SCAFFOLD, f), dst);
    }
  }

  const mode = args.hybrid ? `hybrid → ${args.backend} (${args.dynamicList.length} prefixes)` : "static";
  const kb = Math.max(1, Math.round(statSync(wasm).size / 1024));
  console.log(`✓ staged ${deployDir} (wasm ${kb} KB, ${mode})`);

  // Carry an existing Vercel project linkage so `koru-vercel deploy` pushes to
  // the same project instead of prompting to create a new one.
  if (args.link) {
    const src = join(resolve(args.link), ".vercel", "project.json");
    if (!existsSync(src)) fail(`--link dir has no .vercel/project.json: ${resolve(args.link)}`);
    mkdirSync(join(deployDir, ".vercel"), { recursive: true });
    cpSync(src, join(deployDir, ".vercel", "project.json"));
    const name = JSON.parse(readFileSync(src, "utf-8")).projectName ?? args.link;
    console.log(`  linked to Vercel project: ${name}`);
  }
  console.log(`  next: koru-vercel dev     # local proof`);
  console.log(`  next: koru-vercel deploy  # vercel deploy --prod`);
}

function dev(argv) {
  let proj = ".";
  let port;
  for (const a of argv) {
    if (/^\d+$/.test(a)) port = a;
    else proj = a;
  }
  const deployDir = join(resolve(proj), "deploy");
  const entry = join(deployDir, "test-adapter.mjs");
  if (!existsSync(entry)) fail(`no staged deploy dir at ${deployDir} — run 'koru-vercel build' first`);
  const args = port ? [entry, port] : [entry];
  const r = spawnSync(process.execPath, args, { cwd: deployDir, stdio: "inherit" });
  process.exitCode = r.status ?? 1;
}

function deploy(args) {
  build(args);
  const deployDir = join(resolve(args.proj), "deploy");
  console.log("→ vercel deploy --prod");
  execFileSync("vercel", ["deploy", "--prod", "--yes"], { cwd: deployDir, stdio: "inherit" });
}

const cmd = process.argv[2];
if (!cmd || cmd.startsWith("-")) {
  fail(`usage: koru-vercel <build|dev|deploy> [options] [projDir]\n  (see header of ${process.argv[1]})`);
}
const rest = process.argv.slice(3);
try {
  if (cmd === "build") build(parseArgs(rest));
  else if (cmd === "dev") dev(rest);
  else if (cmd === "deploy") deploy(parseArgs(rest));
  else fail(`unknown command: ${cmd} (expected build|dev|deploy)`);
} catch (err) {
  fail(err?.message ?? String(err));
}
